/**
 * Emits JSON-serialised entity types (as returned by the REST API) into
 * packages/types/src/generated/models.ts so the web apps share exact shapes
 * with the database: Date -> ISO string, Decimal -> string, BigInt -> string.
 */
import { getDMMF } from '@prisma/internals';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const scalar: Record<string, string> = {
  String: 'string',
  Int: 'number',
  BigInt: 'string',
  Boolean: 'boolean',
  Decimal: 'string',
  DateTime: 'string',
  Json: 'unknown',
};
// Never part of an API response.
const HIDDEN: Record<string, string[]> = {
  User: ['passwordHash', 'mfaSecretEnc', 'mfaRecoveryHashes', 'failedLoginCount', 'lockedUntil', 'passwordChangedAt'],
  Customer: ['emiratesIdEnc', 'emiratesIdHash', 'passportNoEnc', 'passportNoHash'],
  Integration: ['secretsEnc'],
  DocumentVersion: ['storageKey', 'encryptionMeta'],
  Session: ['refreshTokenHash'],
  AuthToken: ['tokenHash'],
  DocumentShare: ['tokenHash'],
  ServiceRequest: ['trackingCodeHash'],
};

async function main() {
  const dmmf = await getDMMF({ datamodel: readFileSync(join(__dirname, '..', 'prisma', 'schema.prisma'), 'utf8') });
  const out: string[] = ['// GENERATED by database/scripts/generate-types.ts — do not edit.', '/* eslint-disable */', ''];
  for (const e of dmmf.datamodel.enums) {
    out.push(`export const ${e.name}Values = [${e.values.map((v) => `'${v.name}'`).join(', ')}] as const;`);
    out.push(`export type ${e.name} = (typeof ${e.name}Values)[number];`);
  }
  out.push('');
  for (const m of dmmf.datamodel.models) {
    out.push(`export interface ${m.name} {`);
    for (const f of m.fields) {
      if (f.kind === 'object') continue;
      if (HIDDEN[m.name]?.includes(f.name)) continue;
      const base = f.kind === 'enum' ? f.type : scalar[f.type as string];
      if (!base) throw new Error(`unmapped ${f.type}`);
      out.push(`  ${f.name}: ${base}${f.isList ? '[]' : ''}${f.isRequired || f.isList ? '' : ' | null'};`);
    }
    out.push('}', '');
  }
  const dir = join(__dirname, '..', '..', 'packages', 'types', 'src', 'generated');
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'models.ts'), out.join('\n'));
  console.log(`Wrote ${dmmf.datamodel.models.length} model types.`);
}
main().catch((e) => {
  console.error(e);
  process.exit(1);
});
