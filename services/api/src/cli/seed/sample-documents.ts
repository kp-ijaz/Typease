import PDFDocument from 'pdfkit';
import { eicarTestContent } from '../../modules/documents/malware';

/**
 * Sample files for the demo vault. Every file is generated here, carries a
 * large diagonal watermark and says in plain words that it is not a real
 * document. Nothing is copied from, or made to look like, a genuine identity
 * document: no emblems, no security features, no official layouts.
 */
export const WATERMARK = 'FICTIONAL SAMPLE - NOT A REAL DOCUMENT';

export interface SampleFile {
  filename: string;
  mime: 'application/pdf' | 'image/png';
  content: Buffer;
}

export interface SampleDocumentInput {
  /** Heading, e.g. "Passport copy". */
  title: string;
  /** Lines of "label: value". */
  fields: Array<[string, string]>;
  /** Free text under the fields. */
  note?: string;
  /** Second page with a short body (prepared applications, letters). */
  body?: string[];
}

const slug = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 60);

/** A one- or two-page A5 PDF. Deterministic apart from the PDF's own creation date. */
export function samplePdf(input: SampleDocumentInput): Promise<SampleFile> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A5', margin: 36, info: { Title: `${input.title} (fictional sample)`, Author: 'TypEase demo seed', Subject: WATERMARK } });
    const chunks: Buffer[] = [];
    doc.on('data', (c: Buffer) => chunks.push(c));
    doc.on('error', reject);
    doc.on('end', () => resolve({ filename: `sample-${slug(input.title)}.pdf`, mime: 'application/pdf', content: Buffer.concat(chunks) }));

    const watermark = () => {
      doc.save();
      doc.rotate(-38, { origin: [doc.page.width / 2, doc.page.height / 2] });
      doc.font('Helvetica-Bold').fontSize(25).fillColor('#C0392B').opacity(0.3);
      for (const dy of [-120, 0, 120]) doc.text(WATERMARK, -60, doc.page.height / 2 + dy - 12, { width: doc.page.width + 120, align: 'center', lineBreak: false });
      doc.restore();
      doc.opacity(1).fillColor('#1B2733');
    };
    const footer = () => {
      doc.font('Helvetica').fontSize(7).fillColor('#5B6B7A');
      doc.text('Generated by the TypEase demo seed. Invented data only - no real person, company or authority.', 36, doc.page.height - 52, { width: doc.page.width - 72, align: 'center' });
      doc.fillColor('#1B2733');
    };

    doc.rect(0, 0, doc.page.width, 54).fill('#0B4F6C');
    doc.font('Helvetica-Bold').fontSize(15).fillColor('#FFFFFF').text(`SAMPLE - ${input.title}`, 36, 18, { width: doc.page.width - 72 });
    doc.fillColor('#1B2733');
    let y = 78;
    for (const [label, value] of input.fields) {
      doc.font('Helvetica').fontSize(8).fillColor('#5B6B7A').text(label.toUpperCase(), 36, y);
      doc.font('Helvetica-Bold').fontSize(11).fillColor('#1B2733').text(value, 36, y + 10, { width: doc.page.width - 72 });
      y += 34;
    }
    if (input.note) doc.font('Helvetica-Oblique').fontSize(9).text(input.note, 36, y + 6, { width: doc.page.width - 72 });
    watermark();
    footer();

    if (input.body?.length) {
      doc.addPage();
      doc.font('Helvetica-Bold').fontSize(12).text(`${input.title} - page 2`, 36, 40);
      doc.font('Helvetica').fontSize(10);
      doc.moveDown(0.8);
      for (const paragraph of input.body) doc.text(paragraph, { width: doc.page.width - 72 }).moveDown(0.6);
      watermark();
      footer();
    }
    doc.end();
  });
}

/** A small PNG "scan": a card with initials and a few lines, again watermarked. Used for photos and card-style documents. */
export function samplePng(input: { title: string; initials: string; lines: string[]; tone?: string }): SampleFile {
  // Loaded on demand: the canvas package is only needed by this command.
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  const { createCanvas } = require('@napi-rs/canvas') as typeof import('@napi-rs/canvas');
  const width = 640;
  const height = 400;
  const canvas = createCanvas(width, height);
  const g = canvas.getContext('2d');
  g.fillStyle = '#F4F7FA';
  g.fillRect(0, 0, width, height);
  g.fillStyle = input.tone ?? '#0B4F6C';
  g.fillRect(0, 0, width, 56);
  g.fillStyle = '#FFFFFF';
  g.font = 'bold 22px sans-serif';
  g.fillText(`SAMPLE - ${input.title}`, 20, 36);

  // Neutral placeholder instead of a face.
  g.fillStyle = '#C9D6E2';
  g.fillRect(28, 84, 150, 190);
  g.fillStyle = '#5B6B7A';
  g.font = 'bold 64px sans-serif';
  g.textAlign = 'center';
  g.fillText(input.initials.slice(0, 2).toUpperCase(), 103, 202);
  g.textAlign = 'left';

  g.fillStyle = '#1B2733';
  g.font = '18px sans-serif';
  input.lines.slice(0, 7).forEach((line, i) => g.fillText(line, 204, 112 + i * 28));

  g.save();
  g.translate(width / 2, height / 2);
  g.rotate((-24 * Math.PI) / 180);
  g.globalAlpha = 0.34;
  g.fillStyle = '#C0392B';
  g.font = 'bold 30px sans-serif';
  g.textAlign = 'center';
  for (const dy of [-90, 0, 90]) g.fillText(WATERMARK, 0, dy);
  g.restore();

  g.fillStyle = '#5B6B7A';
  g.font = '12px sans-serif';
  g.fillText('Generated by the TypEase demo seed. Invented data only.', 20, height - 16);
  return { filename: `sample-${slug(input.title)}.png`, mime: 'image/png', content: canvas.toBuffer('image/png') };
}

/** A simple square logo for the white-label demo centre. */
export function sampleLogo(text: string, background: string, foreground = '#FFFFFF'): SampleFile {
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  const { createCanvas } = require('@napi-rs/canvas') as typeof import('@napi-rs/canvas');
  const size = 256;
  const canvas = createCanvas(size, size);
  const g = canvas.getContext('2d');
  g.fillStyle = background;
  g.fillRect(0, 0, size, size);
  g.fillStyle = foreground;
  g.font = 'bold 110px sans-serif';
  g.textAlign = 'center';
  g.textBaseline = 'middle';
  g.fillText(text.slice(0, 2).toUpperCase(), size / 2, size / 2 + 6);
  g.font = 'bold 18px sans-serif';
  g.fillText('DEMO CENTRE', size / 2, size - 28);
  return { filename: 'sample-logo.png', mime: 'image/png', content: canvas.toBuffer('image/png') };
}

/**
 * The industry-standard antivirus TEST file (EICAR) inside a PDF-looking
 * wrapper. It is harmless by design; the vault detects it in-process and
 * quarantines the upload, which is what the demo shows.
 */
export function eicarSample(): SampleFile {
  const content = Buffer.concat([Buffer.from('%PDF-1.4\n% Antivirus TEST file for the TypEase demo (EICAR standard test string, not malware)\n', 'latin1'), eicarTestContent(), Buffer.from('\n%%EOF\n', 'latin1')]);
  return { filename: 'sample-antivirus-test-file.pdf', mime: 'application/pdf', content };
}
