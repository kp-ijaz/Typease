/** Statuses an automation can move a request to: the targets of the `system: true` edges of the state machine. */
export function automaticTargets(transitions: Record<string, Array<{ to: string; system?: boolean }>>): string[] {
  const out = new Set<string>();
  for (const rules of Object.values(transitions)) for (const r of rules) if (r.system) out.add(r.to);
  return [...out];
}
