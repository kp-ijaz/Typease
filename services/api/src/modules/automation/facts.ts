/**
 * What a rule can know about the event that started it.
 *
 *  facts      values the conditions of a rule can test (same rule language as workflows)
 *  variables  `{{placeholders}}` usable in the texts of an action
 *
 * Both are documented per trigger, checked when a rule is saved and exposed
 * by GET /automations/meta so the rule builder never offers something that
 * would be empty at run time.
 */
export type Presence = 'ALWAYS' | 'SOMETIMES' | 'NEVER';

