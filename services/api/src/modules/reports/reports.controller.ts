import { Body, Controller, Delete, Get, HttpCode, Param, ParseUUIDPipe, Patch, Post, Query, Res } from '@nestjs/common';
import { ApiBearerAuth, ApiOperation, ApiProduces, ApiTags } from '@nestjs/swagger';
import {
  createScheduledReportSchema, reportDrilldownQuery, reportExportQuery, reportQuery, scheduledReportListQuery, scheduledReportRunsQuery, updateScheduledReportSchema,
} from '@typease/validation';
import type { Response } from 'express';
import { Permissions } from '../../common/auth/access';
import { SupportSessionRead } from '../../common/auth/support-session';
import { dto } from '../../common/zod';
import { ReportFile, ReportsService } from './reports.service';
import { ScheduledReportsService } from './scheduled-reports.service';

class ReportQueryDto extends dto(reportQuery) {}
class DrilldownDto extends dto(reportDrilldownQuery) {}
class ExportDto extends dto(reportExportQuery) {}
class ScheduleListDto extends dto(scheduledReportListQuery) {}
class ScheduleRunsDto extends dto(scheduledReportRunsQuery) {}
class CreateScheduleDto extends dto(createScheduledReportSchema) {}
class UpdateScheduleDto extends dto(updateScheduledReportSchema) {}

function sendFile(res: Response, file: ReportFile) {
  res.status(200);
  res.setHeader('Content-Type', file.mime);
  res.setHeader('Content-Disposition', `attachment; filename="${file.filename.replace(/[^A-Za-z0-9._-]/g, '_')}"`);
  res.setHeader('Content-Length', String(file.content.length));
  res.setHeader('Cache-Control', 'private, no-store');
  res.setHeader('X-Content-Type-Options', 'nosniff');
  res.end(file.content);
}

/** Declared before ReportsController so that "scheduled" is never read as a report key. */
@ApiTags('Reports')
@ApiBearerAuth()
@Controller('reports/scheduled')
export class ScheduledReportsController {
  constructor(private readonly scheduled: ScheduledReportsService) {}

  @Permissions('report.export')
  @Get()
  @ApiOperation({ summary: 'Scheduled reports the caller may see (their report permission and branch scope apply)' })
  list(@Query() query: ScheduleListDto) {
    return this.scheduled.list(query);
  }
  @Permissions('report.export')
  @Post()
  @ApiOperation({ summary: 'Schedule a report (plan feature "scheduledReports"; recipients must be active staff who may view the report)' })
  create(@Body() body: CreateScheduleDto) {
    return this.scheduled.create(body);
  }
  @Permissions('report.export')
  @Get(':id')
  get(@Param('id', ParseUUIDPipe) id: string) {
    return this.scheduled.get(id);
  }
  @Permissions('report.export')
  @Patch(':id')
  update(@Param('id', ParseUUIDPipe) id: string, @Body() body: UpdateScheduleDto) {
    return this.scheduled.update(id, body);
  }
  @Permissions('report.export')
  @Delete(':id')
  remove(@Param('id', ParseUUIDPipe) id: string) {
    return this.scheduled.remove(id);
  }
  // The generated files are for the people who may view the report, whether or not they may also schedule one.
  @Permissions('report.operational', 'report.financial')
  @Get(':id/runs')
  @ApiOperation({ summary: 'Files generated by this schedule (needs the permission of that report and its branch scope)' })
  runs(@Param('id', ParseUUIDPipe) id: string, @Query() query: ScheduleRunsDto) {
    return this.scheduled.runs(id, query);
  }
  @Permissions('report.operational', 'report.financial')
  @SupportSessionRead('Returns a short-lived link to a generated report file; needs the permission of that report.')
  @Post(':id/runs/:documentId/download-link')
  @HttpCode(200)
  @ApiOperation({ summary: 'Short-lived download link for one generated file (needs the permission of that report; document.read is neither needed nor enough). Audited.' })
  downloadLink(@Param('id', ParseUUIDPipe) id: string, @Param('documentId', ParseUUIDPipe) documentId: string) {
    return this.scheduled.downloadLink(id, documentId);
  }
}

@ApiTags('Reports')
@ApiBearerAuth()
@Controller('reports')
export class ReportsController {
  constructor(private readonly reports: ReportsService) {}

  @Permissions('report.operational', 'report.financial')
  @Get()
  @ApiOperation({ summary: 'The reports the caller may run, with their parameters' })
  list() {
    return this.reports.list();
  }
  @Permissions('report.operational', 'report.financial')
  @Get(':key')
  @ApiOperation({ summary: 'Run a report (403 without the permission of that report)' })
  run(@Param('key') key: string, @Query() query: ReportQueryDto) {
    return this.reports.run(key, query);
  }
  @Permissions('report.operational', 'report.financial')
  @Get(':key/drilldown')
  @ApiOperation({ summary: 'The records behind a report, with ids, paged' })
  drilldown(@Param('key') key: string, @Query() query: DrilldownDto) {
    return this.reports.drilldown(key, query);
  }
  @Permissions('report.export')
  @Get(':key/export')
  @ApiProduces('application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', 'application/pdf', 'text/csv')
  @ApiOperation({ summary: 'Export a report as xlsx, pdf or csv (report.export and the permission of that report). Audited.' })
  async export(@Param('key') key: string, @Query() query: ExportDto, @Res() res: Response) {
    sendFile(res, await this.reports.export(key, query));
  }
}
