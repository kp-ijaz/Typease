import { Logger } from '@nestjs/common';
import { mkdir, open, readdir, readFile, rename, rm, stat, unlink, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve, sep } from 'node:path';
import type { Readable } from 'node:stream';
import { env } from '../../config/env';
import { currentKeyId, decryptBuffer, decryptJson, encryptBuffer, encryptJson, randomToken, sha256, signPayload, verifyPayload } from '../../common/crypto';
import { AtRestEncryption, DownloadOptions, isTenantId, isValidKey, PresignedDownload, PresignedUpload, STAGING_PREFIX, StorageDriver, StoredObjectInfo, UploadConstraints, StorageCheck } from './storage.types';

const MAGIC = Buffer.from('TEV1');

interface FileHeader {
  keyId: string;
  iv: string;
  tag: string;
  size: number;
  contentType: string | null;
}
export interface UploadTicket {
  op: 'put';
  key: string;
  ct: string;
  size: number;
  /** Token id: makes the ticket single use. */
  jti: string;
}
export interface DownloadTicket {
  op: 'get';
  key: string;
  fn: string;
  ct: string;
  disp: 'attachment' | 'inline';
}

export class StorageObjectNotFound extends Error {
  constructor() {
    super('Storage object not found.');
  }
}
/** Thrown by receiveUpload; the controller maps `code` to an HTTP error. */
export class UploadRejected extends Error {
  constructor(
    public readonly code: 'TOO_LARGE' | 'SIZE_MISMATCH' | 'TYPE_MISMATCH' | 'ALREADY_USED' | 'ABORTED',
    message: string,
  ) {
    super(message);
  }
}

/**
 * Files on local disk, encrypted with AES-256-GCM before they are written.
 *
 * "Presigned" URLs are emulated with HMAC-signed, expiring tickets that the API
 * itself serves (see LocalStorageController). The ticket body is additionally
 * encrypted so the object key never appears in a URL in readable form.
 */
export class LocalStorageDriver implements StorageDriver {
  readonly name = 'local' as const;
  readonly encryption: AtRestEncryption = 'APP_AES256_GCM';
  private readonly logger = new Logger(LocalStorageDriver.name);
  readonly root: string;

  constructor(root: string = resolve(env().STORAGE_LOCAL_DIR, 'private')) {
    this.root = root;
  }

  /** The directory exists (or can be created) and a file can be written to it and removed again. */
  async check(): Promise<StorageCheck> {
    const target = `local directory ${this.root}`;
    const probe = join(this.tmpDir, `probe-${randomToken(8)}.tmp`);
    const attempt = (async (): Promise<StorageCheck> => {
      try {
        await mkdir(this.tmpDir, { recursive: true });
        await writeFile(probe, 'ok');
        await unlink(probe);
        return { ok: true, target, error: null };
      } catch (e: any) {
        await unlink(probe).catch(() => undefined);
        return { ok: false, target, error: String(e?.code ?? e?.name ?? 'Error') };
      }
    })();
    // A hanging mount (network file system) must not hang the status page.
    let timer: NodeJS.Timeout | undefined;
    const timeout = new Promise<StorageCheck>((resolve) => {
      timer = setTimeout(() => resolve({ ok: false, target, error: 'TIMEOUT' }), 3000);
    });
    try {
      return await Promise.race([attempt, timeout]);
    } finally {
      if (timer) clearTimeout(timer);
    }
  }

  // ------------------------------------------------------------------ paths
  private pathFor(key: string): string {
    // Keys are generated by us, but validate anyway: a key must never escape the root.
    if (!isValidKey(key)) throw new Error('Invalid storage key.');
    return join(this.root, `${key}.obj`);
  }
  private get tmpDir() {
    return join(this.root, '_tmp');
  }
  private get markerDir() {
    return join(this.root, '_used');
  }

  // ------------------------------------------------------------------ tickets
  private seal(ticket: UploadTicket | DownloadTicket, ttlSeconds: number): string {
    return signPayload({ p: encryptJson(ticket) }, ttlSeconds);
  }
  private open<T extends UploadTicket | DownloadTicket>(token: string, op: T['op']): T | null {
    const outer = verifyPayload<{ p: string }>(token);
    if (!outer || typeof outer.p !== 'string') return null;
    try {
      const ticket = decryptJson<T>(outer.p);
      if (ticket?.op !== op || !isValidKey(ticket.key)) return null;
      return ticket;
    } catch {
      return null;
    }
  }
  openUploadTicket(token: string): UploadTicket | null {
    const t = this.open<UploadTicket>(token, 'put');
    return t && Number.isInteger(t.size) && t.size > 0 && typeof t.jti === 'string' ? t : null;
  }
  openDownloadTicket(token: string): DownloadTicket | null {
    return this.open<DownloadTicket>(token, 'get');
  }

  async presignUpload(key: string, c: UploadConstraints): Promise<PresignedUpload> {
    this.pathFor(key);
    const token = this.seal({ op: 'put', key, ct: c.contentType, size: c.sizeBytes, jti: randomToken(16) }, c.ttlSeconds);
    return {
      url: `${env().API_PUBLIC_URL}/api/v1/storage/local/upload/${token}`,
      method: 'PUT',
      headers: { 'Content-Type': c.contentType },
      expiresAt: new Date(Date.now() + c.ttlSeconds * 1000),
    };
  }
  async presignDownload(key: string, o: DownloadOptions): Promise<PresignedDownload> {
    this.pathFor(key);
    const token = this.seal({ op: 'get', key, fn: o.filename, ct: o.contentType, disp: o.disposition }, o.ttlSeconds);
    return { url: `${env().API_PUBLIC_URL}/api/v1/storage/local/download/${token}`, expiresAt: new Date(Date.now() + o.ttlSeconds * 1000) };
  }

  /**
   * Reads the request body of a ticketed upload. The declared size is enforced
   * while streaming (the body is never buffered beyond it) and the ticket can be
   * redeemed exactly once.
   */
  async receiveUpload(ticket: UploadTicket, body: Readable, headers: { contentType?: string; contentLength?: string }): Promise<void> {
    const declaredType = (headers.contentType ?? '').split(';')[0].trim().toLowerCase();
    if (declaredType !== ticket.ct.toLowerCase()) throw new UploadRejected('TYPE_MISMATCH', `Send the file with Content-Type: ${ticket.ct}.`);
    if (headers.contentLength !== undefined) {
      const length = Number(headers.contentLength);
      if (Number.isFinite(length) && length > ticket.size) throw new UploadRejected('TOO_LARGE', 'The file is larger than the size declared for this upload.');
      if (Number.isFinite(length) && length < ticket.size) throw new UploadRejected('SIZE_MISMATCH', 'The file is smaller than the size declared for this upload.');
    }
    const chunks: Buffer[] = [];
    let received = 0;
    await new Promise<void>((done, fail) => {
      const stop = (err: Error) => {
        body.off('data', onData);
        body.pause();
        fail(err);
      };
      const onData = (chunk: Buffer) => {
        received += chunk.length;
        if (received > ticket.size) return stop(new UploadRejected('TOO_LARGE', 'The file is larger than the size declared for this upload.'));
        chunks.push(chunk);
      };
      body.on('data', onData);
      body.once('end', () => done());
      body.once('error', () => stop(new UploadRejected('ABORTED', 'The upload was interrupted. Please try again.')));
      // 'close' without a preceding 'end' means the client went away mid-upload.
      body.once('close', () => stop(new UploadRejected('ABORTED', 'The upload was interrupted. Please try again.')));
    });
    if (received !== ticket.size) throw new UploadRejected('SIZE_MISMATCH', 'The file is smaller than the size declared for this upload.');

    // Single use: the marker can be created exactly once, even by concurrent requests.
    await mkdir(this.markerDir, { recursive: true });
    try {
      const marker = await open(join(this.markerDir, sha256(ticket.jti)), 'wx');
      await marker.close();
    } catch (e: any) {
      if (e?.code === 'EEXIST') throw new UploadRejected('ALREADY_USED', 'This upload link has already been used.');
      throw e;
    }
    await this.put(ticket.key, Buffer.concat(chunks), ticket.ct);
  }

  // ------------------------------------------------------------------ objects
  async put(key: string, body: Buffer, contentType: string): Promise<void> {
    await this.writeObject(this.pathFor(key), body, contentType);
  }
  private async writeObject(path: string, body: Buffer, contentType: string | null): Promise<void> {
    const { data, meta } = encryptBuffer(body);
    const header = Buffer.from(JSON.stringify({ ...meta, size: body.length, contentType } satisfies FileHeader), 'utf8');
    const length = Buffer.alloc(4);
    length.writeUInt32BE(header.length);
    await mkdir(dirname(path), { recursive: true });
    await mkdir(this.tmpDir, { recursive: true });
    // Write to a temp file first so a crash never leaves a half-written object behind.
    const tmp = join(this.tmpDir, `${randomToken(12)}.tmp`);
    await writeFile(tmp, Buffer.concat([MAGIC, length, header, data]), { mode: 0o600 });
    await rename(tmp, path);
  }

  private async readHeader(path: string): Promise<{ header: FileHeader; offset: number } | null> {
    let handle;
    try {
      handle = await open(path, 'r');
    } catch (e: any) {
      if (e?.code === 'ENOENT') return null;
      throw e;
    }
    try {
      const fixed = Buffer.alloc(8);
      await handle.read(fixed, 0, 8, 0);
      if (!fixed.subarray(0, 4).equals(MAGIC)) throw new Error('Corrupt storage object (bad magic).');
      const headerLength = fixed.readUInt32BE(4);
      if (headerLength > 4096) throw new Error('Corrupt storage object (header).');
      const raw = Buffer.alloc(headerLength);
      await handle.read(raw, 0, headerLength, 8);
      return { header: JSON.parse(raw.toString('utf8')), offset: 8 + headerLength };
    } finally {
      await handle.close();
    }
  }

  async head(key: string): Promise<StoredObjectInfo | null> {
    const found = await this.readHeader(this.pathFor(key));
    return found ? { sizeBytes: found.header.size, contentType: found.header.contentType } : null;
  }

  async getBuffer(key: string): Promise<Buffer> {
    const path = this.pathFor(key);
    const found = await this.readHeader(path);
    if (!found) throw new StorageObjectNotFound();
    const file = await readFile(path);
    // GCM authenticates the content: a tampered or truncated file fails here instead of being served.
    return decryptBuffer(file.subarray(found.offset), found.header);
  }

  async readHead(key: string, bytes: number): Promise<Buffer> {
    return (await this.getBuffer(key)).subarray(0, bytes);
  }

  async move(fromKey: string, toKey: string): Promise<void> {
    const from = this.pathFor(fromKey);
    const to = this.pathFor(toKey);
    await mkdir(dirname(to), { recursive: true });
    try {
      await rename(from, to);
    } catch (e: any) {
      if (e?.code === 'ENOENT') throw new StorageObjectNotFound();
      throw e;
    }
  }

  async delete(key: string): Promise<void> {
    await rm(this.pathFor(key), { force: true });
  }

  async deleteTenant(tenantId: string): Promise<{ removed: number }> {
    // The id becomes a directory name: it must be a UUID and nothing else.
    if (!isTenantId(tenantId)) throw new Error('deleteTenant needs a tenant id.');
    let removed = 0;
    for (const dir of [join(this.root, tenantId), join(this.root, STAGING_PREFIX, tenantId)]) {
      let names: string[];
      try {
        names = await readdir(dir);
      } catch (e: any) {
        if (e?.code === 'ENOENT') continue;
        throw e;
      }
      removed += names.filter((n) => n.endsWith('.obj')).length;
      await rm(dir, { recursive: true, force: true });
    }
    return { removed };
  }

  /**
   * Key rotation: rewrites every object that was encrypted with a key other than the current one (the key id is
   * in the header of each file). Safe to interrupt and to repeat: an object is replaced by rename only after its
   * new version is completely written, and an object that already uses the current key is not touched.
   */
  async reencryptAll(opts: { dryRun?: boolean } = {}): Promise<{ scanned: number; stale: number; reencrypted: number; failed: number; byKeyId: Record<string, number>; failures: string[] }> {
    const report = { scanned: 0, stale: 0, reencrypted: 0, failed: 0, byKeyId: {} as Record<string, number>, failures: [] as string[] };
    const current = currentKeyId();
    const walk = async (dir: string): Promise<void> => {
      let entries;
      try {
        entries = await readdir(dir, { withFileTypes: true });
      } catch (e: any) {
        if (e?.code === 'ENOENT') return;
        throw e;
      }
      for (const entry of entries) {
        const path = join(dir, entry.name);
        if (entry.isDirectory()) {
          if (path === this.tmpDir || path === this.markerDir) continue;
          await walk(path);
          continue;
        }
        if (!entry.name.endsWith('.obj')) continue;
        const key = relative(this.root, path).split(sep).join('/').slice(0, -'.obj'.length);
        try {
          const found = await this.readHeader(path);
          if (!found) continue;
          report.scanned += 1;
          report.byKeyId[found.header.keyId] = (report.byKeyId[found.header.keyId] ?? 0) + 1;
          if (found.header.keyId === current) continue;
          report.stale += 1;
          if (opts.dryRun) continue;
          const plain = decryptBuffer((await readFile(path)).subarray(found.offset), found.header);
          await this.writeObject(path, plain, found.header.contentType);
          report.reencrypted += 1;
        } catch (e: any) {
          report.failed += 1;
          if (report.failures.length < 20) report.failures.push(`${key}: ${e?.name === 'UnknownEncryptionKey' ? `encrypted with key "${e.keyId}", which is not configured` : 'could not be decrypted or rewritten'}`);
        }
      }
    };
    await walk(this.root);
    return report;
  }

  async sweep(olderThanMs: number): Promise<{ removed: number }> {
    let removed = 0;
    const cutoff = Date.now() - olderThanMs;
    for (const dir of [this.markerDir, this.tmpDir]) {
      let names: string[];
      try {
        names = await readdir(dir);
      } catch {
        continue;
      }
      for (const name of names) {
        const path = join(dir, name);
        try {
          if ((await stat(path)).mtimeMs < cutoff) {
            await unlink(path);
            removed += 1;
          }
        } catch (e: any) {
          this.logger.warn(`sweep skipped an entry: ${e?.code ?? e?.message}`);
        }
      }
    }
    return { removed };
  }
}
