const isPair = (value: Pair | Pairs): value is Pair => Array.isArray(value);
function split(source: Pairs, index: 0 | 1): Dictionary {
  const out: Dictionary = {};
  for (const [key, value] of Object.entries(source)) {
    if (isPair(value)) out[key] = value[index];
    else out[key] = split(value, index);
  }
  return out;
}

