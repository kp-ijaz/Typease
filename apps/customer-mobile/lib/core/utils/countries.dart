/// ISO 3166-1 alpha-2 country codes with English and Arabic names, for the
/// `country` field type of dynamic service forms. The API stores the code.
class Country {
  const Country(this.code, this.en, this.ar);

  final String code;
  final String en;
  final String ar;

  String name(String languageCode) => languageCode == 'ar' ? ar : en;
}

