  /// The label for a stored code; the code itself when it is not in the list.
  static String nameOf(String code, String languageCode) {
    final upper = code.toUpperCase();
    for (final country in all) {
      if (country.code == upper) return country.name(languageCode);
    }
    return code;
  }

  /// Sorted by name in the given language, with the UAE first.
  static List<Country> sorted(String languageCode) {
    final list = List<Country>.of(all);
    list.sort((a, b) {
      if (a.code == 'AE') return -1;
      if (b.code == 'AE') return 1;
      return a.name(languageCode).compareTo(b.name(languageCode));
    });
    return list;
  }

